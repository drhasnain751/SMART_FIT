// src/pages/AIPlanner/PlanDisplay.jsx
import React, { useState, useEffect } from 'react';
import { Typography } from '../../components/Typography';
import { 
  Calendar,
  Flame,
  Drumstick,
  Wheat,
  Droplet,
  TrendingUp,
  CheckCircle2,
  Sparkles,
  Brain,
  Clock,
  Target,
  Award,
  ChevronDown,
  ChevronUp,
  Download,
  FileText,
  Printer
} from 'lucide-react';

const PlanDisplay = ({ plan }) => {
  // Updated: independent toggles for meals and days
  const [expandedDays, setExpandedDays] = useState({});
  const [expandedMeals, setExpandedMeals] = useState({});
  const [showAnimation, setShowAnimation] = useState(false);

  useEffect(() => {
    if (plan) {
      setShowAnimation(true);
      // Optional: reset expanded states when a new plan is loaded
      setExpandedDays({});
      setExpandedMeals({});
    }
  }, [plan]);

  if (!plan) return null;

  const { workout, diet } = plan;

  // Fixed MacroCard with better contrast
  const MacroCard = ({ icon: Icon, label, value, iconColor, bgColor, borderColor }) => (
    <div className={`${bgColor} rounded-2xl p-6 border-2 ${borderColor} hover:shadow-xl transition-all duration-300 transform hover:scale-105`}>
      <div className={`w-12 h-12 ${iconColor} rounded-xl flex items-center justify-center mb-3 shadow-lg`}>
        <Icon className="w-6 h-6 text-white" />
      </div>
      <p className="text-sm text-gray-600 font-medium mb-1">{label}</p>
      <p className="text-3xl font-bold text-gray-900">
        {value}
      </p>
    </div>
  );

  // Download functionality
  const handleDownload = () => {
    const planText = generatePlanText();
    const blob = new Blob([planText], { type: 'text/plain' });
    const url = window.URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'My-AI-Fitness-Plan.txt';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    window.URL.revokeObjectURL(url);
  };

  const handlePrint = () => {
    window.print();
  };

  const generatePlanText = () => {
    let text = '═══════════════════════════════════════════\n';
    text += '     🧠 AI-POWERED FITNESS PLAN\n';
    text += '═══════════════════════════════════════════\n\n';
    
    // Diet Plan
    text += '📊 DAILY NUTRITION TARGETS\n';
    text += '─────────────────────────────────────────\n';
    text += `🔥 Calories: ${diet.daily_targets.calories} kcal\n`;
    text += `🥩 Protein: ${diet.daily_targets.protein}g\n`;
    text += `🌾 Carbs: ${diet.daily_targets.carbs}g\n`;
    text += `🥑 Fats: ${diet.daily_targets.fat}g\n\n`;
    
    text += '🍽️ MEAL PLAN\n';
    text += '═══════════════════════════════════════════\n\n';
    
    Object.entries(diet.diet_plan).forEach(([mealName, mealDetails]) => {
      text += `${mealName.toUpperCase()}\n`;
      text += '─────────────────────────────────────────\n';
      mealDetails.items.forEach((item, index) => {
        text += `${index + 1}. ${item.Food}\n`;
        text += `   Portion: ${item['Portion (g)']}g | Calories: ${item.Calories} kcal\n`;
      });
      text += '\n';
    });
    
    // Workout Plan
    text += '💪 WEEKLY WORKOUT PLAN\n';
    text += '═══════════════════════════════════════════\n\n';
    
    Object.entries(workout.workout_plan).forEach(([day, exercises]) => {
      text += `${day.toUpperCase()}\n`;
      text += '─────────────────────────────────────────\n';
      exercises.forEach((ex, index) => {
        text += `${index + 1}. ${ex.Exercise} - ${ex.SetsReps}\n`;
      });
      text += '\n';
    });
    
    text += '═══════════════════════════════════════════\n';
    text += '   Generated by AI Fitness Planner v2.0\n';
    text += '═══════════════════════════════════════════\n';
    
    return text;
  };

  return (
    <>
      <div className={`plan-content space-y-8 transition-all duration-700 ${showAnimation ? 'opacity-100 translate-y-0' : 'opacity-0 translate-y-10'}`}>
        {/* Success Header */}
        <div className="relative overflow-hidden bg-gradient-to-r from-purple-600 via-pink-600 to-cyan-600 rounded-3xl p-8 text-white shadow-2xl print:rounded-none">
          <div className="absolute top-0 right-0 w-64 h-64 bg-white/10 rounded-full -mr-32 -mt-32"></div>
          <div className="absolute bottom-0 left-0 w-48 h-48 bg-white/10 rounded-full -ml-24 -mb-24"></div>
          
          <div className="relative z-10 flex items-center gap-4">
            <div className="w-16 h-16 bg-white/20 backdrop-blur-xl rounded-2xl flex items-center justify-center animate-bounce print:animate-none">
              <Brain className="w-8 h-8" />
            </div>
            <div>
              <div className="flex items-center gap-2 mb-2">
                <CheckCircle2 className="w-6 h-6" />
                <span className="text-sm font-medium opacity-90">AI Generation Complete</span>
              </div>
              <h2 className="text-3xl font-bold">Your Personalized Plan is Ready! 🎉</h2>
              <p className="mt-2 opacity-90">Powered by advanced AI algorithms tailored just for you</p>
            </div>
          </div>
        </div>

        {/* Diet Plan Section */}
        <div className="print:break-inside-avoid">
          <div className="flex items-center gap-3 mb-6">
            <div className="p-3 bg-gradient-to-br from-orange-500 to-red-600 rounded-xl shadow-lg">
              <Drumstick className="w-6 h-6 text-white" />
            </div>
            <div>
              <h3 className="text-2xl font-bold text-gray-900">AI-Optimized Nutrition Plan</h3>
              <p className="text-sm text-gray-600 flex items-center gap-1">
                <Sparkles className="w-4 h-4 text-yellow-500" />
                Calculated for maximum results
              </p>
            </div>
          </div>

          {/* Daily Targets */}
          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4 mb-8 print:grid-cols-4">
            <MacroCard
              icon={Flame}
              label="Daily Calories"
              value={`${diet.daily_targets.calories}`}
              iconColor="bg-gradient-to-br from-orange-500 to-red-600"
              bgColor="bg-white"
              borderColor="border-orange-200 hover:border-orange-400"
            />
            <MacroCard
              icon={Drumstick}
              label="Protein"
              value={`${diet.daily_targets.protein}g`}
              iconColor="bg-gradient-to-br from-red-500 to-pink-600"
              bgColor="bg-white"
              borderColor="border-red-200 hover:border-red-400"
            />
            <MacroCard
              icon={Wheat}
              label="Carbs"
              value={`${diet.daily_targets.carbs}g`}
              iconColor="bg-gradient-to-br from-yellow-500 to-orange-600"
              bgColor="bg-white"
              borderColor="border-yellow-200 hover:border-yellow-400"
            />
            <MacroCard
              icon={Droplet}
              label="Fats"
              value={`${diet.daily_targets.fat}g`}
              iconColor="bg-gradient-to-br from-blue-500 to-cyan-600"
              bgColor="bg-white"
              borderColor="border-blue-200 hover:border-blue-400"
            />
          </div>

          {/* Meal Plans - independent toggles + no stretch */}
          <div className="grid grid-cols-1 lg:grid-cols-2 gap-6 items-start print:grid-cols-1">
            {Object.entries(diet.diet_plan).map(([mealName, mealDetails], index) => {
              const isExpanded = !!expandedMeals[mealName];
              const mealIcons = {
                Breakfast: '🌅',
                Lunch: '☀️',
                Dinner: '🌙',
                Snacks: '🍎'
              };

              return (
                <div
                  key={mealName}
                  className="bg-white rounded-2xl shadow-xl border-2 border-gray-100 hover:border-purple-300 transition-all duration-300 print:break-inside-avoid print:mb-4"
                  style={{ animationDelay: `${index * 100}ms` }}
                >
                  <button
                    type="button"
                    onClick={() =>
                      setExpandedMeals(prev => ({ ...prev, [mealName]: !prev[mealName] }))
                    }
                    className="w-full p-6 flex items-center justify-between hover:bg-gradient-to-r hover:from-purple-50 hover:to-pink-50 transition-all duration-300 print:hidden"
                  >
                    <div className="flex items-center gap-4">
                      <span className="text-4xl">{mealIcons[mealName] || '🍽️'}</span>
                      <div className="text-left">
                        <h4 className="text-xl font-bold text-gray-900">{mealName}</h4>
                        <p className="text-sm text-gray-500">{mealDetails.items.length} items</p>
                      </div>
                    </div>
                    {isExpanded ? (
                      <ChevronUp className="w-5 h-5 text-gray-400" />
                    ) : (
                      <ChevronDown className="w-5 h-5 text-gray-400" />
                    )}
                  </button>

                  {/* Print: Always show header */}
                  <div className="hidden print:block p-6 border-b-2 border-gray-200">
                    <div className="flex items-center gap-4">
                      <span className="text-4xl">{mealIcons[mealName] || '🍽️'}</span>
                      <div>
                        <h4 className="text-xl font-bold text-gray-900">{mealName}</h4>
                        <p className="text-sm text-gray-500">{mealDetails.items.length} items</p>
                      </div>
                    </div>
                  </div>

                  {/* Content (toggles independently) */}
                  {isExpanded && (
                    <div className="px-6 pb-6 bg-gradient-to-b from-transparent to-gray-50 print:block">
                      <div className="space-y-3">
                        {mealDetails.items.map((item, itemIndex) => (
                          <div
                            key={itemIndex}
                            className="flex items-center justify-between p-4 bg-white rounded-xl border border-gray-200 hover:border-purple-300 hover:shadow-md transition-all duration-200"
                          >
                            <div className="flex-1">
                              <p className="font-semibold text-gray-900">{item.Food}</p>
                              <p className="text-sm text-gray-500 mt-1">
                                <span className="inline-flex items-center gap-1">
                                  <Target className="w-3 h-3" />
                                  {item['Portion (g)']}g
                                </span>
                              </p>
                            </div>
                            <div className="flex items-center gap-2 px-4 py-2 bg-gradient-to-r from-orange-100 to-red-100 rounded-lg">
                              <Flame className="w-4 h-4 text-orange-600" />
                              <span className="font-bold text-orange-700">{item.Calories}</span>
                            </div>
                          </div>
                        ))}
                      </div>
                    </div>
                  )}

                  {/* Print: Always show content */}
                  <div className="hidden print:block px-6 pb-6">
                    <div className="space-y-3">
                      {mealDetails.items.map((item, itemIndex) => (
                        <div
                          key={itemIndex}
                          className="flex items-center justify-between p-4 bg-white rounded-xl border border-gray-200"
                        >
                          <div className="flex-1">
                            <p className="font-semibold text-gray-900">{item.Food}</p>
                            <p className="text-sm text-gray-500 mt-1">
                              Portion: {item['Portion (g)']}g
                            </p>
                          </div>
                          <div className="flex items-center gap-2 px-4 py-2 bg-gray-100 rounded-lg">
                            <span className="font-bold text-gray-700">{item.Calories} kcal</span>
                          </div>
                        </div>
                      ))}
                    </div>
                  </div>
                </div>
              );
            })}
          </div>
        </div>

        {/* Workout Plan Section */}
        <div className="print:break-before-page">
          <div className="flex items-center gap-3 mb-6 mt-12 print:mt-0">
            <div className="p-3 bg-gradient-to-br from-purple-500 to-cyan-600 rounded-xl shadow-lg">
              <TrendingUp className="w-6 h-6 text-white" />
            </div>
            <div>
              <h3 className="text-2xl font-bold text-gray-900">AI-Generated Workout Plan</h3>
              <p className="text-sm text-gray-600 flex items-center gap-1">
                <Sparkles className="w-4 h-4 text-yellow-500" />
                Designed to match your goals and equipment
              </p>
            </div>
          </div>

          <div className="grid grid-cols-1 gap-6">
            {Object.entries(workout.workout_plan).map(([day, exercises], index) => {
              const isExpanded = !!expandedDays[day];
              const dayEmojis = {
                Monday: '💪',
                Tuesday: '🔥',
                Wednesday: '⚡',
                Thursday: '🚀',
                Friday: '💯',
                Saturday: '🎯',
                Sunday: '🌟'
              };

              return (
                <div
                  key={day}
                  className="bg-white rounded-2xl shadow-xl border-2 border-gray-100 hover:border-cyan-300 transition-all duration-300 print:break-inside-avoid print:mb-4"
                  style={{ animationDelay: `${index * 100}ms` }}
                >
                  <button
                    type="button"
                    onClick={() =>
                      setExpandedDays(prev => ({ ...prev, [day]: !prev[day] }))
                    }
                    className="w-full p-6 flex items-center justify-between hover:bg-gradient-to-r hover:from-cyan-50 hover:to-purple-50 transition-all duration-300 print:hidden"
                  >
                    <div className="flex items-center gap-4">
                      <div className="w-14 h-14 bg-gradient-to-br from-cyan-500 to-purple-600 rounded-xl flex items-center justify-center shadow-lg">
                        <span className="text-2xl">{dayEmojis[day] || '📅'}</span>
                      </div>
                      <div className="text-left">
                        <h4 className="text-xl font-bold text-gray-900 flex items-center gap-2">
                          {day}
                          <span className="px-3 py-1 bg-cyan-100 text-cyan-700 text-xs font-semibold rounded-full">
                            {exercises.length} exercises
                          </span>
                        </h4>
                        <p className="text-sm text-gray-500 flex items-center gap-1 mt-1">
                          <Clock className="w-4 h-4" />
                          ~{exercises.length * 3} minutes
                        </p>
                      </div>
                    </div>
                    {isExpanded ? (
                      <ChevronUp className="w-5 h-5 text-gray-400" />
                    ) : (
                      <ChevronDown className="w-5 h-5 text-gray-400" />
                    )}
                  </button>

                  {/* Print: Always show header */}
                  <div className="hidden print:block p-6 border-b-2 border-gray-200">
                    <div className="flex items-center gap-4">
                      <div className="w-14 h-14 bg-gradient-to-br from-cyan-500 to-purple-600 rounded-xl flex items-center justify-center">
                        <span className="text-2xl">{dayEmojis[day] || '📅'}</span>
                      </div>
                      <div>
                        <h4 className="text-xl font-bold text-gray-900">{day}</h4>
                        <p className="text-sm text-gray-500">
                          {exercises.length} exercises • ~{exercises.length * 3} minutes
                        </p>
                      </div>
                    </div>
                  </div>

                  {/* Content (toggles independently) */}
                  {isExpanded && (
                    <div className="px-6 pb-6 bg-gradient-to-b from-transparent to-gray-50 print:block">
                      <div className="space-y-3">
                        {exercises.map((ex, exIndex) => (
                          <div
                            key={exIndex}
                            className="group flex items-center gap-4 p-4 bg-white rounded-xl border border-gray-200 hover:border-cyan-300 hover:shadow-lg transition-all duration-200"
                          >
                            <div className="w-10 h-10 bg-gradient-to-br from-cyan-100 to-purple-100 rounded-lg flex items-center justify-center font-bold text-cyan-700 group-hover:scale-110 transition-transform">
                              {exIndex + 1}
                            </div>
                            <div className="flex-1">
                              <p className="font-semibold text-gray-900 group-hover:text-cyan-700 transition-colors">
                                {ex.Exercise}
                              </p>
                            </div>
                            <div className="px-4 py-2 bg-gradient-to-r from-cyan-100 to-purple-100 rounded-lg">
                              <span className="font-bold text-cyan-700">{ex.SetsReps}</span>
                            </div>
                          </div>
                        ))}
                      </div>
                    </div>
                  )}

                  {/* Print: Always show content */}
                  <div className="hidden print:block px-6 pb-6">
                    <div className="space-y-3">
                      {exercises.map((ex, exIndex) => (
                        <div
                          key={exIndex}
                          className="flex items-center gap-4 p-4 bg-white rounded-xl border border-gray-200"
                        >
                          <div className="w-10 h-10 bg-gray-100 rounded-lg flex items-center justify-center font-bold text-gray-700">
                            {exIndex + 1}
                          </div>
                          <div className="flex-1">
                            <p className="font-semibold text-gray-900">
                              {ex.Exercise}
                            </p>
                          </div>
                          <div className="px-4 py-2 bg-gray-100 rounded-lg">
                            <span className="font-bold text-gray-700">{ex.SetsReps}</span>
                          </div>
                        </div>
                      ))}
                    </div>
                  </div>
                </div>
              );
            })}
          </div>
        </div>

        {/* DOWNLOAD SECTION */}
        <div className="bg-gradient-to-br from-purple-50 via-pink-50 to-cyan-50 rounded-3xl p-8 border-2 border-purple-200 no-print">
          <div className="text-center mb-6">
            <div className="inline-flex items-center justify-center w-16 h-16 bg-gradient-to-br from-purple-600 to-cyan-600 rounded-2xl mb-4 shadow-lg">
              <Download className="w-8 h-8 text-white" />
            </div>
            <h3 className="text-2xl font-bold text-gray-900 mb-2">Save Your Plan</h3>
            <p className="text-gray-600">Download or print your personalized fitness plan</p>
          </div>

          <div className="flex flex-col sm:flex-row gap-4 justify-center">
            <button
              onClick={handleDownload}
              className="group flex items-center justify-center gap-3 px-8 py-4 bg-gradient-to-r from-purple-600 to-pink-600 text-white rounded-xl font-semibold shadow-lg hover:shadow-xl transform hover:scale-105 transition-all duration-300"
            >
              <FileText className="w-5 h-5 group-hover:animate-bounce" />
              <span>Download as Text</span>
              <Download className="w-5 h-5" />
            </button>

            <button
              onClick={handlePrint}
              className="group flex items-center justify-center gap-3 px-8 py-4 bg-gradient-to-r from-cyan-600 to-blue-600 text-white rounded-xl font-semibold shadow-lg hover:shadow-xl transform hover:scale-105 transition-all duration-300"
            >
              <Printer className="w-5 h-5 group-hover:animate-bounce" />
              <span>Print Plan</span>
            </button>
          </div>
        </div>

        {/* AI Badge Footer */}
        <div className="flex items-center justify-center gap-2 py-8 no-print">
          <Award className="w-5 h-5 text-yellow-500" />
          <p className="text-gray-600 font-medium">
            Plan generated by <span className="bg-gradient-to-r from-purple-600 to-cyan-600 bg-clip-text text-transparent font-bold">AI Engine v3.0</span>
          </p>
          <Sparkles className="w-5 h-5 text-yellow-500 animate-pulse" />
        </div>
      </div>

      {/* Print Styles */}
      <style>{`
        @media print {
          @page {
            margin: 1cm;
            size: A4;
          }
          
          .no-print {
            display: none !important;
          }
          
          .plan-content {
            max-width: 100% !important;
          }
          
          button {
            display: none !important;
          }
          
          .print\\:hidden {
            display: none !important;
          }
          
          .print\\:block {
            display: block !important;
          }
          
          .print\\:break-before-page {
            break-before: page;
          }
          
          .print\\:break-inside-avoid {
            break-inside: avoid;
          }
          
          .shadow-xl, .shadow-lg, .shadow-2xl {
            box-shadow: none !important;
          }
          
          * {
            -webkit-print-color-adjust: exact !important;
            print-color-adjust: exact !important;
          }
        }
      `}</style>
    </>
  );
};

export default PlanDisplay;